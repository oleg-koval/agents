import { createHash } from 'node:crypto';
import { lstat, mkdir, readFile, readdir, rename, unlink, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = fileURLToPath(new URL('../', import.meta.url));
const digest = (body) => createHash('sha256').update(body).digest('hex');
const marker = '# Generated by oleg-koval/agents; sha256=';
const anchor = (path) => `shared-${path.replace(/[^a-zA-Z0-9]/g, '-')}`;
const links = /\[([^\]]+)\]\(([^)]+)\)/g;

export async function generate(source = root) {
  const names = (await readdir(join(source, 'roles'))).filter((n) => /^olko-[a-z-]+\.md$/.test(n)).sort();
  const result = new Map();
  for (const file of names) {
    const bundled = new Map();
    async function include(path) {
      if (bundled.has(path)) return;
      if (!/^(roles|pipelines)\/[a-z-]+\.md$/.test(path)) throw new Error(`Unsupported shared reference: ${path}`);
      const body = await readFile(join(source, path), 'utf8');
      bundled.set(path, ''); // Break reference cycles before recursion.
      const references = [];
      const rewritten = body.replace(links, (match, label, target) => {
        if (/^(https?:|#)/.test(target)) return match;
        const [location, fragment] = target.split('#');
        const next = relative(source, resolve(source, dirname(path), location));
        references.push(next);
        return `[${label}](#${anchor(next)})${fragment ? ` (section: ${fragment})` : ''}`;
      });
      bundled.set(path, `<a id="${anchor(path)}"></a>\n${rewritten.trim()}`);
      for (const next of references) await include(next);
    }
    await include(`roles/${file}`);
    const original = await readFile(join(source, 'roles', file), 'utf8');
    const name = file.slice(0, -3);
    const description = original.split('\n\n')[1].split(/(?<=\.)\s/)[0];
    const instructions = [
      "Read the target project's current AGENTS.md and applicable nested instructions before acting. Target-specific instructions take precedence over this shared guidance. Follow host permissions and the user's authorized scope; a role does not authorize delegation or external actions.",
      'The following shared documents are bundled references. Apply the primary role; consult linked roles and pipelines only when relevant. Internal links refer to sections in this instruction bundle, not files in the target project. Project-specific skills, commands and endpoints must come from the target project.',
      ...bundled.values(),
    ].join('\n\n');
    // JSON basic strings are TOML basic strings for this controlled text corpus.
    const body = `name = ${JSON.stringify(name)}\ndescription = ${JSON.stringify(description)}\ndeveloper_instructions = ${JSON.stringify(instructions)}\n`;
    result.set(`${name}.toml`, `${marker}${digest(body)}\n${body}`);
  }
  return result;
}

async function stat(path) {
  try { return await lstat(path); } catch (error) { if (error.code !== 'ENOENT') throw error; }
}

async function checkParents(destination) {
  for (let path = resolve(destination); ; path = dirname(path)) {
    const info = await stat(path);
    if (info && (!info.isDirectory() || info.isSymbolicLink())) throw new Error(`Unsafe destination directory: ${path}`);
    if (dirname(path) === path) break;
  }
}

export async function install(destination, { dryRun = false, source = root } = {}) {
  await checkParents(destination);
  const files = await generate(source);
  const actions = [];
  for (const [name, content] of files) {
    const path = join(destination, name);
    const info = await stat(path);
    let previous;
    if (info) {
      if (!info.isFile() || info.isSymbolicLink()) throw new Error(`Conflict: ${path}`);
      previous = await readFile(path, 'utf8');
      if (previous !== content) {
        const newline = previous.indexOf('\n');
        if (previous.slice(0, newline) !== marker + digest(previous.slice(newline + 1))) throw new Error(`Conflict: ${path}`);
      }
    }
    actions.push({ path, content, previous, action: previous === content ? 'unchanged' : info ? 'update' : 'create' });
  }
  // Preflight every file before writing anything. Never delete stale or unrelated files.
  if (!dryRun) {
    await mkdir(destination, { recursive: true });
    for (const item of actions.filter((item) => item.action !== 'unchanged')) {
      const current = await stat(item.path);
      if (current?.isSymbolicLink() || (current && !current.isFile()) ||
          (current ? await readFile(item.path, 'utf8') : undefined) !== item.previous) throw new Error(`Destination changed: ${item.path}`);
      if (!current) {
        await writeFile(item.path, item.content, { flag: 'wx' });
      } else {
        const temporary = `${item.path}.${process.pid}.tmp`;
        await writeFile(temporary, item.content, { flag: 'wx' });
        try { await rename(temporary, item.path); } catch (error) { await unlink(temporary); throw error; }
      }
    }
  }
  return actions.map(({ path, action }) => `${dryRun ? 'dry-run ' : ''}${action}: ${path}`);
}

async function main(args) {
  let destination;
  let dryRun = false;
  for (let i = 0; i < args.length; i++) {
    const option = args[i];
    if (option === '--dry-run') { dryRun = true; continue; }
    if (destination) throw new Error('Choose exactly one destination');
    if (option === '--global') destination = join(process.env.CODEX_HOME || join(homedir(), '.codex'), 'agents');
    else if (['--project', '--output'].includes(option) && args[i + 1] && !args[i + 1].startsWith('--')) {
      destination = resolve(args[++i]);
      if (option === '--project') destination = join(destination, '.codex', 'agents');
    } else throw new Error('Usage: node scripts/codex-agents.mjs (--global | --project PATH | --output DIR) [--dry-run]');
  }
  if (!destination) throw new Error('A destination is required');
  console.log((await install(destination, { dryRun })).join('\n'));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => { console.error(error.message); process.exitCode = 1; });
}
